"""Compile a validated local named-expression snapshot; never writes hardware."""
import argparse
import json
from pathlib import Path
import sys
from convert_gork_motion import convert
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'03-Src/stopwatch-voice-companion'))
from companion.motion import MotionLibrary, NAMES, watch_token

def export(record):
    if not record['entries']:raise ValueError('表情库为空')
    text='// Generated by tools/export_watch_expressions.py; SPDX-License-Identifier: AGPL-3.0-only\n#pragma once\n#include "motion_scene.h"\n#include <cstddef>\nnamespace gork_custom_motion {\n'
    text+='struct Entry {const char* id;const char* name;const char* token;uint8_t scene;MotionParams scenes[4];};\n'
    text+=f'constexpr uint32_t kLibraryRevision = {record["revision"]}u;\n'
    text+='constexpr Entry entries[] = {\n'
    manifest=[]
    def number(v):
        value=format(float(v),'.9g');return value+('f' if '.' in value or 'e' in value else '.0f')
    def array(values):return '{'+','.join(map(number,values))+'}'
    for entry in record['entries']:
        token=watch_token(entry)
        if any(item['token']==token for item in manifest):raise ValueError('表情参数标识冲突')
        text+=' {'+','.join(json.dumps(entry[k],ensure_ascii=False) for k in ('id','name'))+','+json.dumps(token)+','+str(NAMES.index(entry['scene']))+',{\n'
        for scene in convert(entry['config'])['scenes']:
            text+='  {'+','.join(array(scene[k]) for k in ('eyes','motion','props'))+'},\n'
        text+=' }},\n'
        manifest.append({k:entry[k] for k in ('id','name','scene')}|{'token':token,'config':entry['config']})
    text+='};\nconstexpr size_t kCount = sizeof(entries)/sizeof(entries[0]);\n}\n'
    return text,{'schema':'gork-watch-expressions','version':1,'revision':record['revision'],'entries':manifest}

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source',type=Path,default=ROOT/'03-Src/stopwatch-voice-companion/motion-library.local.json')
    parser.add_argument('--output',type=Path,default=ROOT/'03-Src/stopwatch-grok-avatar/src/custom_expressions.h')
    parser.add_argument('--check',action='store_true');args=parser.parse_args()
    # Validate the explicit source without creating/recovering or writing a library.
    record=MotionLibrary(args.source)._record(args.source)
    code,manifest=export(record)
    if args.check:
        assert args.output.read_text(encoding='utf-8')==code,'Watch表情快照与当前库不同'
        assert json.loads(args.output.with_suffix('.watch.json').read_text(encoding='utf-8'))==manifest
    else:
        args.output.write_text(code,encoding='utf-8',newline='\n')
        args.output.with_suffix('.watch.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    print(f'Compiled {len(record["entries"])} independent expressions at library revision {record["revision"]}; no hardware write')
if __name__=='__main__':main()
