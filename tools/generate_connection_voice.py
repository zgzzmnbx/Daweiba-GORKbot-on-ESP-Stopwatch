"""Generate the two user-authorized Qwen connection cues once, then export PCM.

Run with the existing voice-runtime interpreter. API credentials stay in the
dedicated environment variable. Existing WAVs are reused; never retry a failed
cloud request automatically. No device/session operations are performed.
"""
from pathlib import Path
import argparse
import asyncio
import io
import json
import sys
import wave

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / '03-Src/voice-service/03-Src'))
from voice_service.config import load_settings
from voice_service.cloud import CloudEngines
import numpy as np

ASSETS = ROOT / '03-Src/stopwatch-grok-avatar/assets/connection-voice'
HEADER = ROOT / '03-Src/stopwatch-grok-avatar/src/connection_voice.h'
PHRASES = [('Wifi', 'Wi-Fi 已连接。'), ('Ble', '蓝牙已连接。')]


async def generate(allow_cloud):
    ASSETS.mkdir(parents=True, exist_ok=True)
    settings = load_settings()
    engine = CloudEngines(settings)
    entries = []
    arrays = []
    for name, text in PHRASES:
        path = ASSETS / (name.lower() + '.wav')
        if not path.exists():
            if not allow_cloud:
                raise SystemExit('Missing WAV: explicitly pass --generate for authorized cloud generation')
            result = await engine.run('tts', {'text': text, 'cloud_voice': 'Ethan',
                                             'speed': 1., 'sample_rate': 16000})
            path.write_bytes(result['result']['audio'])
        with wave.open(io.BytesIO(path.read_bytes()), 'rb') as wav:
            if (wav.getnchannels(), wav.getsampwidth(), wav.getframerate()) != (1, 2, 16000):
                raise ValueError('Cue must be 16 kHz mono PCM16')
            pcm = np.frombuffer(wav.readframes(wav.getnframes()), dtype='<i2').copy()
        if not 0 < len(pcm) <= 16000 * 6 or np.max(np.abs(pcm.astype(np.int32))) < 100:
            raise ValueError('Cue duration or signal invalid')
        # Match existing Watch speech enhancement: at most 3x, peak <=30000;
        # firmware uses Unity codec gain for speech. Never trim phonemes.
        peak = int(np.max(np.abs(pcm.astype(np.int32))))
        gain = min(3., 30000 / peak)
        pcm = np.rint(pcm.astype(np.float64) * gain).astype('<i2')
        lines = [','.join(map(str, pcm[i:i+24])) for i in range(0, len(pcm), 24)]
        arrays.append('static const int16_t k' + name + '[] = {\n' + ',\n'.join(lines) + '\n};\n')
        entries.append({'id': name.lower(), 'text': text, 'model': settings.cloud_tts_model,
                        'voice': 'Ethan', 'sample_rate': 16000, 'samples': len(pcm),
                        'seconds': round(len(pcm)/16000, 3), 'pcm_gain': round(gain, 6),
                        'source': path.name})
    HEADER.write_text('// Generated by tools/generate_connection_voice.py; do not edit.\n'
                      '// User-authorized Qwen3-TTS-Flash / Ethan fixed connection phrases.\n'
                      '#pragma once\n#include <stdint.h>\n#include <stddef.h>\n'
                      'namespace gork_connection_voice {\n' + '\n'.join(arrays) + '}\n', encoding='utf-8')
    (ASSETS / 'source.json').write_text(json.dumps(entries, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(entries, ensure_ascii=False))


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--generate', action='store_true')
    asyncio.run(generate(parser.parse_args().generate))
