"""Deterministic v2 JSON -> Watch parameters and C++ source; never connects to hardware."""
import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / '03-Src/stopwatch-voice-companion'))
from companion.motion import validate, parse, NAMES, ASSETS

PENS = ('quill', 'nib', 'pencil', 'brush')


def geometry():
    renderer = (ROOT / '03-Src/stopwatch-grok-avatar/src/grok_renderer.cpp').read_text(encoding='utf-8')
    inset = int(re.search(r'kBodyInset\s*=\s*(\d+)', renderer)[1])
    presets = (ASSETS.parent / 'avatar-presets.js').read_text(encoding='utf-8')
    data = json.JSONDecoder().raw_decode(presets[presets.index('const presets=') + len('const presets='):])[0]
    body = next(p['body']['primary'] for p in data if p['id'] == 'gork')
    if body['type'] != 'sphere' or body['width'] != body['height'] or body['width'] != body['depth']:
        raise ValueError('Watch 动效适配只支持当前 Gork 球体')
    drawing = (ASSETS / 'gork-renderer.js').read_text(encoding='utf-8')
    a, b = map(float, re.search(r'ctx\.scale\((\d+)/(\d+)', drawing).groups())
    # Perspective silhouette of the pinned sphere, matching the engine's camera distance.
    engine = (ASSETS.parent / 'avatar-engine.js').read_text(encoding='utf-8')
    camera = float(re.search(r'M=(\d+),_e=', engine)[1])
    sphere = body['width'] / 2
    radius = sphere / (1 - (sphere / camera) ** 2) ** .5 * a / b
    return {'bodyInset': inset, 'sphereRadius': sphere, 'cameraDistance': camera,
            'eyeGeometryScale': a / b, 'desktopHeadRadius': radius}


def convert(config, revision=1, size=466):
    config = validate(config)
    if type(revision) is not int or not 1 <= revision <= 2**32-1:
        raise ValueError('Watch 修订号须为 1..UINT32_MAX')
    if type(size) is not int or not 64 <= size <= 1024:
        raise ValueError('屏幕尺寸无效')
    g = geometry()
    radius = size / 2 - g['bodyInset']
    fields = json.loads((ASSETS / 'field-specs.json').read_text(encoding='utf-8'))
    scenes = []
    for name in NAMES:
        source = config['scenes'][name]
        props = [] if name == 'idle' else [source[name][k] for k in fields[name]]
        if name == 'writing':
            props[-1] = PENS.index(props[-1])
        scenes.append({'name': name, 'eyes': [source['eyes'][k] for k in fields['eyes']],
                       'motion': [source['motion'][k] for k in fields['motion']],
                       'props': props + [0] * (6 - len(props))})
    return {'schema': 'gork-watch-motion', 'version': 1, 'sourceVersion': 2, 'revision': revision,
            'geometry': {**g, 'screenSize': size, 'center': [size/2, size/2],
                         'bodyRadius': radius, 'desktopToWatchScale': radius / g['desktopHeadRadius']},
            'scenes': scenes}


def cpp(result):
    f = lambda v: format(float(v), '.9g') + ('f' if '.' in format(float(v), '.9g') or 'e' in format(float(v), '.9g') else '.0f')
    arr = lambda xs: '{' + ','.join(map(f, xs)) + '}'
    g = result['geometry']
    text = '// Generated by tools/convert_gork_motion.py from validated user configuration.\n'
    text += '// SPDX-License-Identifier: AGPL-3.0-only\n#pragma once\n#include "motion_scene.h"\nnamespace gork_motion_config {\n'
    text += f'constexpr uint32_t kRevision = {result["revision"]}u;\n'
    for name in ('sphereRadius', 'cameraDistance', 'eyeGeometryScale', 'desktopHeadRadius'):
        text += f'constexpr float {name} = {f(g[name])};\n'
    text += f'constexpr int bodyInset = {g["bodyInset"]};\n'
    text += 'constexpr MotionParams scenes[4] = {\n'
    for scene in result['scenes']:
        text += '  {' + ','.join(arr(scene[k]) for k in ('eyes','motion','props')) + '}, // ' + scene['name'] + '\n'
    text += '};\n'
    specs = json.loads((ASSETS / 'field-specs.json').read_text(encoding='utf-8'))
    for key, bound in (('minimum',1),('maximum',2)):
        text += f'constexpr MotionParams {key}[4] = {{\n'
        for name in NAMES:
            props = [] if name == 'idle' else [0 if isinstance(v[1],list) and bound==1 else 3 if isinstance(v[1],list) else v[bound] for v in specs[name].values()]
            text += '  {' + ','.join(arr(xs) for xs in ([v[bound] for v in specs['eyes'].values()], [v[bound] for v in specs['motion'].values()], props+[0]*(6-len(props)))) + '},\n'
        text += '};\n'
    return text + '} // namespace gork_motion_config\n'


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--source', type=Path, default=ASSETS/'initial-config.gork.json')
    p.add_argument('--output', type=Path, default=ROOT/'03-Src/stopwatch-grok-avatar/src/motion_config.h')
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    text = args.source.read_text(encoding='utf-8')
    source = json.loads(text)
    if type(source) is dict and set(source) == {'revision','config'}:
        config, revision = validate(source['config']), source['revision']
    else:
        config, revision = parse(text), 1
    result = convert(config, revision)
    code = cpp(result)
    if args.check:
        assert args.output.read_text(encoding='utf-8') == code, 'Watch generated parameters are stale'
    else:
        args.output.parent.mkdir(parents=True,exist_ok=True)
        args.output.write_text(code,encoding='utf-8',newline='\n')
        args.output.with_suffix('.watch.json').write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    print(f'Watch v1/source v2 r{revision}: 4 scenes, all fields; center={result["geometry"]["center"]}, radius={result["geometry"]["bodyRadius"]}, no device write')


if __name__ == '__main__':
    main()
